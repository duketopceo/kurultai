#!/usr/bin/env node
// Bake the Brain v2 cortex from src/assets/brain.glb (run from website/: node --experimental-strip-types ../scripts/bake-cortex.mjs; needs website/node_modules).
// Output: src/brain/v2/cortexData.ts (generated, committed): a decimated low-poly mesh (wireframe + fresnel
// shell), an interior voxel mask (placement hull), and K lobe seeds (k-means over the interior = the
// contiguous tag regions). Deterministic. Not part of the runtime bundle build.
import fs from 'node:fs';
import { createRequire } from 'node:module';
const { MeshoptSimplifier } = createRequire(import.meta.url)('../website/node_modules/meshoptimizer/index.js');
import { bakeSdfFromPositions } from '../website/src/brain/layout/sdf.ts';

const TARGET_TRIS = Number(process.env.TARGET_TRIS || 2000);
const RES = 40;
const LOBES = 24;
const glb = fs.readFileSync(new URL('../website/src/assets/brain.glb', import.meta.url));
const jl = glb.readUInt32LE(12);
const json = JSON.parse(glb.subarray(20, 20 + jl).toString());
const bin = glb.subarray(20 + jl + 8);
const acc = json.accessors, bv = json.bufferViews;
const read = (a, Ctor) => { const v = bv[a.bufferView]; const off = bin.byteOffset + (v.byteOffset || 0) + (a.byteOffset || 0); return new Ctor(bin.buffer.slice(off, off + a.count * (a.type === 'VEC3' ? 3 : 1) * Ctor.BYTES_PER_ELEMENT)); };
let pos = read(acc[0], Float32Array);
let idx = Uint32Array.from(read(acc[1], Uint16Array));

// weld + normalise to ~unit half-extent, centred on the bbox
await MeshoptSimplifier.ready;
const remap = MeshoptSimplifier.generatePositionRemap(pos, 3);
idx = idx.map((i) => remap[i]);
const mn = [Infinity, Infinity, Infinity], mx = [-Infinity, -Infinity, -Infinity];
for (let i = 0; i < pos.length; i += 3) for (let k = 0; k < 3; k++) { mn[k] = Math.min(mn[k], pos[i + k]); mx[k] = Math.max(mx[k], pos[i + k]); }
const ctr = mn.map((v, k) => (v + mx[k]) / 2);
const half = Math.max(...mx.map((v, k) => (v - mn[k]) / 2));
const S = 0.95 / half;
for (let i = 0; i < pos.length; i += 3) for (let k = 0; k < 3; k++) pos[i + k] = (pos[i + k] - ctr[k]) * S;
console.log('extent', mx.map((v, k) => +((v - mn[k]) * S).toFixed(3)));

// interior mask from the full-res mesh
const sdf = bakeSdfFromPositions(pos, idx, RES);
const inside = new Uint8Array(RES ** 3);
let nIn = 0;
for (let i = 0; i < inside.length; i++) if (sdf.values[i] < 0) { inside[i] = 1; nIn++; }
console.log('interior voxels', nIn, 'cell', sdf.cell.toFixed(4));

// decimate
const [dIdx] = MeshoptSimplifier.simplify(idx, pos, 3, TARGET_TRIS * 3, 0.03, ['ErrorAbsolute']);
// rebuild the vertex list by first-use order (indices still address the welded source positions)
const used = new Map(); const outPos = [];
const outIdx = new Uint16Array(dIdx.length);
for (let i = 0; i < dIdx.length; i++) {
  const v = dIdx[i];
  if (!used.has(v)) { used.set(v, used.size); outPos.push(pos[v * 3], pos[v * 3 + 1], pos[v * 3 + 2]); }
  outIdx[i] = used.get(v);
}
console.log('decimated tris', dIdx.length / 3, 'verts', used.size);

// k-means over interior voxel centres; farthest-point init keeps consecutive lobes spread apart
const pts = [];
for (let z = 0; z < RES; z++) for (let y = 0; y < RES; y++) for (let x = 0; x < RES; x++) if (inside[x + RES * (y + RES * z)]) pts.push([sdf.originX + x * sdf.cell, sdf.originY + y * sdf.cell, sdf.originZ + z * sdf.cell]);
const d2 = (a, b) => (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2;
const seeds = [pts.reduce((b, p) => (p[0] > b[0] ? p : b), pts[0]).slice()]; // start anterior-most-x (arbitrary but deterministic)
while (seeds.length < LOBES) {
  let best = null, bd = -1;
  for (const p of pts) { let m = Infinity; for (const s of seeds) m = Math.min(m, d2(p, s)); if (m > bd) { bd = m; best = p; } }
  seeds.push(best.slice());
}
for (let it = 0; it < 16; it++) {
  const sum = seeds.map(() => [0, 0, 0, 0]);
  for (const p of pts) { let b = 0, bd = Infinity; seeds.forEach((s, i) => { const d = d2(p, s); if (d < bd) { bd = d; b = i; } }); sum[b][0] += p[0]; sum[b][1] += p[1]; sum[b][2] += p[2]; sum[b][3]++; }
  sum.forEach((s, i) => { if (s[3]) seeds[i] = [s[0] / s[3], s[1] / s[3], s[2] / s[3]]; });
}
const r4 = (v) => +v.toFixed(4);
const b64 = (arr) => Buffer.from(arr.buffer, arr.byteOffset, arr.byteLength).toString('base64');
// pack mask bits
const bits = new Uint8Array(Math.ceil(RES ** 3 / 8));
for (let i = 0; i < inside.length; i++) if (inside[i]) bits[i >> 3] |= 1 << (i & 7);
// quantise positions to int16 over [-1,1]
const q = new Int16Array(outPos.length);
for (let i = 0; i < q.length; i++) q[i] = Math.round(Math.max(-1, Math.min(1, outPos[i])) * 32767);
const src = `// GENERATED by scripts/bake-cortex.mjs from src/assets/brain.glb. Do not edit.
// ${used.size} verts, ${dIdx.length / 3} tris, ${RES}^3 interior mask (${nIn} voxels), ${LOBES} lobe seeds.
export const CORTEX_MESH_POS = '${b64(q)}'; // int16 xyz, /32767
export const CORTEX_MESH_IDX = '${b64(outIdx)}'; // uint16 triangles
export const CORTEX_MASK_BITS = '${b64(bits)}'; // ${RES}^3 bit mask, x fastest
export const CORTEX_GRID = { res: ${RES}, origin: [${r4(sdf.originX)}, ${r4(sdf.originY)}, ${r4(sdf.originZ)}] as [number, number, number], cell: ${r4(sdf.cell)} };
export const CORTEX_LOBE_SEEDS: [number, number, number][] = ${JSON.stringify(seeds.map((s) => s.map(r4)))};
`;
fs.writeFileSync(new URL('../website/src/brain/v2/cortexData.ts', import.meta.url), src);
console.log('wrote', src.length, 'bytes');
